/* ═══════ مِداد — إصلاح النص العربي «المعكوس» في ملفات PDF ═══════
   بعض ملفات PDF (مُصدَّرة من برامج تنضيد بخطوط عربية ناقصة الجداول) تُخرج الحرفين المتّصلين
   برسمة واحدة (lam-alef، لم، لح، في، على…) بترتيب معكوس: «المبحث» ← «املبحث»، «السلام» ← «السالم»،
   «إلى» ← «إىل»، «في» ← «يف». الكتاب يُقرأ سليماً لكن البحث داخله يتعثّر.
   detect(): هل النص من هذا النوع؟ (علامات لا تقع في نصّ سليم أبداً)
   fix(): يصحّح الأنماط القاطعة وقائمة الكلمات الشائعة — ولا يُطبَّق إلا على نصّ ثبت تلفه. */
const ArFix = (() => {
  const L = 'ء-يٮ-ۓ'; // حروف عربية (بلا حركات)
  const WORD = new RegExp(`[${L}ً-ٰٟ]+`, 'g');
  const MARKS = /[ً-ٰٟ]/g;

  // علامات التلف: «ى» يتبعها حرف، و«يف/عىل/إىل» كلمات مستقلة، و«ال» وحدها، و«األ/اإل» في أول الكلمة
  function stats(text) {
    let words = 0, bad = 0;
    for (const m of String(text || '').matchAll(WORD)) {
      const w = m[0].replace(MARKS, '');
      if (!w) continue;
      words++;
      if (/ى[ء-ي]/.test(w) || /^[وف]?(يف|ال)$/.test(w) || /^[وفبكل]?ا[أإآ]/.test(w)) bad++;
    }
    return { words, bad };
  }
  // نصّ سليم لا يكاد يحوي أيّاً منها؛ النص المعكوس يحويها في نحو ٥٪ من كلماته
  function detect(text) {
    const s = stats(text);
    return s.words >= 80 && s.bad >= 8 && s.bad / s.words > 0.008;
  }

  // كلمات شائعة تلفها غير قابل للاستنتاج بقاعدة عامة (المعكوس ← الصحيح)
  const WORDS = {
    'عيل': 'علي', 'يل': 'لي', 'مل': 'لم', 'هلم': 'لهم', 'هلا': 'لها', 'هلن': 'لهن', 'هبا': 'بها', 'هبم': 'بهم', 'هبذا': 'بهذا', 'هبذه': 'بهذه',
    'غري': 'غير', 'خري': 'خير', 'الخري': 'الخير', 'غريه': 'غيره', 'غريها': 'غيرها', 'كثري': 'كثير', 'كثرية': 'كثيرة', 'الكثري': 'الكثير', 'كبري': 'كبير', 'كبرية': 'كبيرة', 'الكبري': 'الكبير',
    'اهلل': 'الله', 'هلل': 'لله', 'باهلل': 'بالله', 'واهلل': 'والله', 'ألن': 'لأن', 'ألنه': 'لأنه', 'ألهنا': 'لأنها', 'ألهنم': 'لأنهم', 'إلن': 'لأن',
    'هناية': 'نهاية', 'إهنا': 'إنها', 'إهنم': 'إنهم', 'أهنا': 'أنها', 'أهنم': 'أنهم',
    'السالم': 'السلام', 'سالم': 'سلام', 'إسالم': 'إسلام', 'الإسالم': 'الإسلام', 'الكالم': 'الكلام', 'كالم': 'كلام', 'السالمة': 'السلامة', 'إسالمي': 'إسلامي', 'الإسالمي': 'الإسلامي', 'الإسالمية': 'الإسلامية', 'إسالمية': 'إسلامية',
    'الرشيعة': 'الشريعة', 'رشيعة': 'شريعة', 'الرشعية': 'الشرعية', 'رشعية': 'شرعية', 'الرشعي': 'الشرعي', 'رشعي': 'شرعي', 'الرشع': 'الشرع', 'الرشيف': 'الشريف', 'الرشيفة': 'الشريفة', 'رشيف': 'شريف',
    'الصالة': 'الصلاة', 'صالة': 'صلاة', 'الصالح': 'الصلاح', 'األخالق': 'الأخلاق', 'الأخالق': 'الأخلاق', 'أخالق': 'أخلاق', 'خالل': 'خلال', 'خالف': 'خلاف', 'الخالفة': 'الخلافة', 'خالفة': 'خلافة',
    'سليامن': 'سليمان',
  };
  // («بني» لا تُصحَّح إلى «بين»: صحيحة أيضاً كما في «بني هاشم»)

  function fixWord(w0) {
    // كلمة بحركات: نصلح هيكلها؛ فإن تغيّر أعدناه بلا حركات (البحث يتجاهلها أصلاً)، وإلا أبقيناها كما هي
    const bare = w0.replace(MARKS, '');
    if (bare !== w0) { const f = fixBare(bare); return f === bare ? w0 : f; }
    return fixBare(w0);
  }
  function fixBare(w0) {
    let w = w0;
    // ١) «ى» لا تقع إلا آخر الكلمة: «ىل» ← «لى» (على، إلى، تعالى، مستوى…)
    w = w.replace(/ى([ء-ي])/g, '$1ى');
    // ٢) أداة التعريف مع همزة: «األ/اإل/اآل» ← «الأ/الإ/الآ» (مع السوابق و ف ب ك)
    w = w.replace(/^([وفبك]?)ا([أإآ])/, '$1ال$2');
    // ٣) أداة التعريف مع م/ح/ج/خ: «املـ/احلـ/اجلـ/اخلـ» ← «المـ/الحـ/الجـ/الخـ» (بعدها حرفان على الأقل)
    w = w.replace(/^([وفبك]?)ا([محجخ])ل(?=[ء-ي]{2})/, '$1ال$2');
    // ٤) «لا»: «ال» وحدها، و«وال/فال/إال/أال»، وتنوين «ـالً» في الآخر
    if (/^[وف]?ال$/.test(w)) w = w.slice(0, -2) + 'لا';
    else if (w === 'إال' || w === 'أال') w = w[0] + 'لا';
    // ٥) «في»: «يف/ويف/فيف»
    if (/^[وف]?يف$/.test(w)) w = w.slice(0, -2) + 'في';
    return WORDS[w] || w;
  }

  function fix(text) {
    return String(text || '')
      .replace(WORD, (w) => fixWord(w))
      .replace(/الً/g, 'لاً'); // «أوالً/مثالً» ← «أولاً/مثلاً»
  }

  return { detect, fix, stats };
})();
window.ArFix = ArFix;
